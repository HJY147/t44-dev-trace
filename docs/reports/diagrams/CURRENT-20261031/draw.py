class Fig:
 def __init__(self,id,title,sub='',w=2200,h=1400):
  self.id=id;self.w=w;self.h=h;self.im=Image.new('RGB',(w,h),'white');self.d=ImageDraw.Draw(self.im);self.svg=[]
  self.line([(50,35),(w-50,35)],TEAL,9);self.text((65,95),title,56,anchor='lm');self.text((65,160),sub,31,GRAY,anchor='lm')
 def text(self,p,s,size=38,color=NAVY,anchor='mm'):
  f=ImageFont.truetype(FONT,size);lines=s.split('\n');step=size*1.36;y=p[1]-(len(lines)-1)*step/2 if anchor=='mm' else p[1]
  for st in lines:
   self.d.text((p[0],y),st,font=f,fill=color,anchor=anchor)
   self.svg.append(f'<text x="{p[0]}" y="{y}" text-anchor="'+('middle'if anchor=='mm'else'start')+f'" dominant-baseline="middle" font-family="Heiti SC,sans-serif" font-size="{size}" fill="{color}">{html.escape(st)}</text>');y+=step
 def box(self,x,y,w,h,s,fill=PALE,size=38,stroke=TEAL):
  self.d.rounded_rectangle((x,y,x+w,y+h),radius=20,fill=fill,outline=stroke,width=3);self.svg.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="20" fill="{fill}" stroke="{stroke}" stroke-width="3"/>');self.text((x+w/2,y+h/2),s,size)
 def line(self,ps,color=TEAL,width=4,arrow=False,label=None,lp=None):
  self.d.line(ps,fill=color,width=width,joint='curve');self.svg.append('<polyline points="'+' '.join(f'{x},{y}'for x,y in ps)+f'" fill="none" stroke="{color}" stroke-width="{width}"/>')
  if arrow:
   x,y=ps[-1];a=math.atan2(y-ps[-2][1],x-ps[-2][0]);q=[(x,y),(x-22*math.cos(a-.42),y-22*math.sin(a-.42)),(x-22*math.cos(a+.42),y-22*math.sin(a+.42))];self.d.polygon(q,fill=color);self.svg.append('<polygon points="'+' '.join(f'{xx},{yy}'for xx,yy in q)+f'" fill="{color}"/>')
  if label:self.text(lp or ((ps[0][0]+ps[-1][0])/2,(ps[0][1]+ps[-1][1])/2-28),label,30,color)
 def end(self,note):
  self.text((65,self.h-60),note,29,GRAY,anchor='lm');self.im.save(OUT/(self.id+'.png'));(OUT/(self.id+'.svg')).write_text(f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.w}" height="{self.h}" viewBox="0 0 {self.w} {self.h}">'+''.join(self.svg)+'</svg>')

